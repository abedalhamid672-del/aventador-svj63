// Dev tool: turns OpenStreetMap raceway ways (assets-src/ring.osm.json, © OpenStreetMap
// contributors, ODbL) into the Nordschleife outline used by the Ring section.
//   node tools/build-ring-path.mjs
import fs from 'node:fs';

const { elements } = JSON.parse(fs.readFileSync('assets-src/ring.osm.json', 'utf8'));

// Ways that belong to the GP circuit, pit lanes, link roads or the rallycross loop.
const EXCLUDE = /Boxengasse|Sprintstrecke|Müllenbach|Rallycross|Anbindung|Variante|Michael-Schumacher|Goodyear|Ford-Kurve|NGK/i;
const START = 'Hatzenbach';

const ways = elements
  .filter((w) => !EXCLUDE.test(w.tags.name ?? '') && w.tags.raceway !== 'pitlane')
  // `out geom` carries coordinates, not node ids; shared junctions have identical coordinates.
  .map((w) => ({ id: w.id, name: w.tags.name ?? '', nodes: w.geometry.map((p) => `${p.lat},${p.lon}`), pts: w.geometry }));

const byFirstNode = new Map();
for (const w of ways) (byFirstNode.get(w.nodes[0]) ?? byFirstNode.set(w.nodes[0], []).get(w.nodes[0])).push(w);

// Walk one-way segments end-to-start, preferring named Nordschleife corners at junctions.
const start = ways.find((w) => w.name === START);
const loop = [start];
const used = new Set([start.id]);
let last = start;
for (let guard = 0; guard < 400; guard++) {
  const endNode = last.nodes.at(-1);
  if (endNode === start.nodes[0]) break;
  const options = (byFirstNode.get(endNode) ?? []).filter((w) => !used.has(w.id));
  if (!options.length) throw new Error(`Dead end after ${last.name || last.id}`);
  const next = options.sort((a, b) => Number(!!b.name) - Number(!!a.name) || b.pts.length - a.pts.length)[0];
  loop.push(next);
  used.add(next.id);
  last = next;
}
if (last.nodes.at(-1) !== start.nodes[0]) throw new Error('Loop did not close');

// Equirectangular projection around the track's mean latitude, in metres.
const pts = loop.flatMap((w, i) => (i === 0 ? w.pts : w.pts.slice(1)));
const lat0 = (pts.reduce((a, p) => a + p.lat, 0) / pts.length) * (Math.PI / 180);
const R = 6371000;
const xy = pts.map((p) => [R * (p.lon * Math.PI / 180) * Math.cos(lat0), -R * (p.lat * Math.PI / 180)]);

// Perimeter in metres, as a sanity check against the official 20.8 km figure.
let perimeter = 0;
for (let i = 1; i < xy.length; i++) perimeter += Math.hypot(xy[i][0] - xy[i - 1][0], xy[i][1] - xy[i - 1][1]);

// Douglas–Peucker simplification (tolerance in metres).
function simplify(points, tol) {
  if (points.length < 3) return points;
  const [a, b] = [points[0], points.at(-1)];
  let maxD = 0, idx = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const p = points[i];
    const len = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
    const d = Math.abs((b[0] - a[0]) * (a[1] - p[1]) - (a[0] - p[0]) * (b[1] - a[1])) / len;
    if (d > maxD) { maxD = d; idx = i; }
  }
  if (maxD <= tol) return [a, b];
  return [...simplify(points.slice(0, idx + 1), tol).slice(0, -1), ...simplify(points.slice(idx), tol)];
}
// A closed loop has coincident endpoints (a zero-length baseline), so simplify each half.
const mid = Math.floor(xy.length / 2);
const simple = [...simplify(xy.slice(0, mid + 1), 6).slice(0, -1), ...simplify(xy.slice(mid), 6)];

// Fit into a 1000-unit-wide viewBox.
const xs = simple.map((p) => p[0]), ys = simple.map((p) => p[1]);
const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
const scale = 1000 / (maxX - minX);
const W = 1000, H = Math.round((maxY - minY) * scale);
const fit = simple.map(([x, y]) => [((x - minX) * scale).toFixed(1), ((y - minY) * scale).toFixed(1)]);
const d = `M${fit.map((p) => p.join(' ')).join('L')}Z`;

const out = `/**
 * Nürburgring Nordschleife outline, generated by tools/build-ring-path.mjs from OpenStreetMap
 * raceway data (© OpenStreetMap contributors, ODbL). Starts at Hatzenbach, runs clockwise.
 */
export const RING_TRACK = {
  viewBox: '0 0 ${W} ${H}',
  width: ${W},
  height: ${H},
  d: '${d}',
} as const;
`;
fs.writeFileSync('src/data/ringTrack.ts', out);
console.log({ ways: loop.length, corners: loop.map((w) => w.name).filter(Boolean).join(' › '), rawPoints: pts.length, points: simple.length, perimeterKm: +(perimeter / 1000).toFixed(2), viewBox: `0 0 ${W} ${H}`, bytes: out.length });
